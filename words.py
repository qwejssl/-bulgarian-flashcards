def get_all_words():
    words = []
    for cat_id, cat in WORD_CATEGORIES.items():
        for w in cat["words"]:
            words.append({**w, "category": cat["name"], "cat_id": cat_id})
    return words


def get_category_words(cat_id: str):
    if cat_id not in WORD_CATEGORIES:
        return []
    return WORD_CATEGORIES[cat_id]["words"]


def get_total_count():
    return sum(len(c["words"]) for c in WORD_CATEGORIES.values())
